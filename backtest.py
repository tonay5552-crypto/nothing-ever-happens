def generate_synthetic_markets(
    *,
    n: int = 500,
    seed: int = 42,
    start: date = date(2024, 1, 1),
) -> pd.DataFrame:
    """Generate a deterministic synthetic universe that roughly matches the
    empirical No-bias edge: ~72% of non-sports markets resolve NO. Useful for
    offline unit tests and smoke runs when real parquet data isn't present."""

    rng = np.random.default_rng(seed)
    categories = [
        "politics",
        "tech",
        "macro",
        "entertainment",
        "crypto",
        "sports",
        "nba",
        "nfl",
    ]
    rows = []
    for i in range(n):
        cat = categories[int(rng.integers(0, len(categories)))]
        duration = int(rng.integers(7, 120))
        start_d = start + timedelta(days=int(rng.integers(0, 400)))
        end_d = start_d + timedelta(days=duration)
        is_sport = cat in {"sports", "nba", "nfl", "football"}
        # No-bias edge: non-sports resolve NO with ~0.72 probability.
        no_prob = 0.52 if is_sport else 0.72
        outcome = "no" if rng.random() < no_prob else "yes"
        no_entry = float(rng.uniform(0.35, 0.85))
        # If market will resolve no, peak probably climbs high before close.
        no_peak = min(0.99, no_entry + float(rng.uniform(0.0, 0.45)))
        if outcome == "yes":
            no_peak = min(no_peak, 0.9)
        rows.append(
            {
                "market_id": f"syn-{i:05d}",
                "title": f"{cat.title()} synthetic market #{i}",
                "category": cat,
                "start_date": start_d,
                "end_date": end_d,
                "resolved": True,
                "outcome": outcome,
                "no_entry_price": no_entry,
                "no_peak_price": no_peak,
                "binary": True,
            }
        )
    return pd.DataFrame(rows)


