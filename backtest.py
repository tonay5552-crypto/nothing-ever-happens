"""Backtest engine for the 'nothing ever happens' No-bias Polymarket strategy.

This module is intentionally self-contained so it can be used both by the live
bot for offline evaluation and by ``optimizer.py`` during the Karpathy-style
autoresearch loop.

Data pipeline (priority order):

1. Parquet files under ``--data-dir`` (default ``data/polymarket``) from
   https://github.com/jon-becker/prediction-market-analysis (2026 clean
   Polymarket dataset).
2. CSV fallback under the same directory for Kaggle Polymarket dumps.
3. Synthetic fixture data generated by ``--synthetic`` (used by tests / smoke
   runs when no real dataset is available).

Universe filter (mirrors the live bot's strategy):

* Only resolved markets (``resolved == True``)
* Only standalone binary yes/no markets
* Category / title must not match any configured blacklist entry (default:
  "sports", "nba", "nfl", "football")
* Market duration (``end_date - start_date``) >= ``min_market_days``

Simulation:

* Enter **one** NO position per qualifying market at the first observed no-ask
  below ``no_price_cap`` after the ``min_market_days`` cooldown. Entry price is
  adjusted up by the configured slippage percentage.
* Position size = ``position_size_pct`` of the current bankroll, capped so
  concurrent notional stays under ``max_open_positions_pct`` of the bankroll.
* Hard ceiling of ``max_trade_count_per_day`` new entries per calendar day.
* Exit when the NO mid-price reaches ``exit_threshold`` (take-profit) or at
  resolution, whichever comes first. YES resolution = NO pays 1.0, NO resolves
  = position stops out at 0. A ``taker_fee_pct`` is charged on both legs.

Metrics output (see :class:`BacktestResult`):

* Total PnL (USD), Win Rate %, Sharpe Ratio (annualised), Max Drawdown %, Trade
  Count, Avg Hold Days.

Usage:

    python backtest.py --data-dir data/polymarket --config config.json

or from Python:

    from backtest import BacktestEngine, BacktestParams
    engine = BacktestEngine.from_directory("data/polymarket")
    result = engine.run(BacktestParams())
    print(result.summary_dict())
"""

