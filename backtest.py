def _load_config_file(path: Path | str) -> dict[str, Any]:
    p = Path(path)
    if not p.exists():
        return {}
    with p.open() as f:
        return json.load(f)


def _parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--data-dir",
        default=os.getenv("POLYMARKET_DATA_DIR", "data/polymarket"),
        help="Directory with .parquet / .csv market dumps (default: %(default)s).",
    )
    parser.add_argument(
        "--config",
        default="config.json",
        help="Path to config.json (falls back to config.example.json).",
    )
    parser.add_argument(
        "--synthetic",
        action="store_true",
        help="Use deterministic synthetic data (offline smoke test).",
    )
    parser.add_argument(
        "--synthetic-n",
        type=int,
        default=500,
        help="Number of synthetic markets to generate (default: %(default)s).",
    )
    parser.add_argument(
        "--walk-forward-splits",
        type=int,
        default=0,
        help="If > 0, print per-fold walk-forward metrics as well.",
    )
    parser.add_argument(
        "--output-json",
        default=None,
        help="Optional path to write the summary dict as JSON.",
    )
    parser.add_argument(
        "--max-files",
        type=int,
        default=None,
        help="Optional cap on number of data files to read (useful for quick smoke runs).",
    )
    return parser.parse_args(list(argv) if argv is not None else None)


def main(argv: Sequence[str] | None = None) -> int:
    logging.basicConfig(
        level=os.getenv("LOG_LEVEL", "INFO"),
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
    )
    args = _parse_args(argv)
    cfg = _load_config_file(args.config) or _load_config_file("config.example.json")
    params = BacktestParams.from_config_dict(cfg)

    if args.synthetic:
        engine = BacktestEngine.from_dataframe(
            generate_synthetic_markets(n=args.synthetic_n)
        )
    else:
        engine = BacktestEngine.from_directory(args.data_dir, max_files=args.max_files)

    result = engine.run(params)
    summary = result.summary_dict()
    print(json.dumps({"params": asdict(params), "result": summary}, indent=2, default=str))

    if args.walk_forward_splits and args.walk_forward_splits > 1:
        folds = engine.walk_forward(params, splits=args.walk_forward_splits)
        print(json.dumps(
            {
                "walk_forward": [r.summary_dict() for r in folds],
            },
            indent=2,
        ))

    if args.output_json:
        Path(args.output_json).parent.mkdir(parents=True, exist_ok=True)
        with open(args.output_json, "w") as f:
            json.dump({"params": asdict(params), "result": summary}, f, indent=2, default=str)

    return 0


if __name__ == "__main__":
    sys.exit(main())
